export function lonLatToXY(lon: number, lat: number, w: number, h: number) {
  return [((lon + 180) / 360) * w, ((90 - lat) / 180) * h] as const;
}

function points(ring: LonLat[], w: number, h: number) {
  return ring.map(([lon, lat]) => lonLatToXY(lon, lat, w, h));
}

/** Midpoint-quadratic outline — sculptural, not polyline teeth. */
export function pathD(ring: LonLat[], w: number, h: number) {
  const pts = points(ring, w, h);
  if (pts.length < 2) return "";
  const mid = (a: readonly [number, number], b: readonly [number, number]) =>
    [(a[0] + b[0]) / 2, (a[1] + b[1]) / 2] as const;
  let d = `M${pts[0][0].toFixed(1)} ${pts[0][1].toFixed(1)}`;
  for (let i = 0; i < pts.length; i += 1) {
    const cur = pts[i];
    const next = pts[(i + 1) % pts.length];
    const m = mid(cur, next);
    d += ` Q${cur[0].toFixed(1)} ${cur[1].toFixed(1)} ${m[0].toFixed(1)} ${m[1].toFixed(1)}`;
  }
  return `${d} Z`;
}

function traceRing(g: CanvasRenderingContext2D, ring: LonLat[], w: number, h: number) {
  const pts = points(ring, w, h);
  if (pts.length < 2) return;
  g.moveTo((pts[0][0] + pts[pts.length - 1][0]) / 2, (pts[0][1] + pts[pts.length - 1][1]) / 2);
  for (let i = 0; i < pts.length; i += 1) {
    const cur = pts[i];
    const next = pts[(i + 1) % pts.length];
    g.quadraticCurveTo(cur[0], cur[1], (cur[0] + next[0]) / 2, (cur[1] + next[1]) / 2);
  }
  g.closePath();
}

